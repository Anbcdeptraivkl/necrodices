"""Compilation sheets for art review: every unit, hunter and item with its name, how it is
obtained (combo / role / kind) and where its art comes from.

    python tools/art/compile_sheets.py      # writes docs/art_sheets/{units,hunters,items,dice}.png + README.md

Sheets are drawn at 1x in the game palette and upscaled ×2 (nearest), so pixels stay crisp.
Names and combinations are read from data/ and data/text/, so the sheets follow the designer's
text edits. Nothing under assets/ is written.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

sys.path.insert(0, str(Path(__file__).resolve().parent))
from pixelgrid import ROOT  # noqa: E402
from palette import rgba  # noqa: E402

OUT = ROOT / "docs" / "art_sheets"
DATA = ROOT / "data"
FONT = ImageFont.truetype(str(ROOT / "assets/fonts/fusion_pixel/fusion_pixel_8px.otf"), 8)
CARD = (204, 46)
COLS = 4
KIND_COLOUR = {"RELIC": "G1", "POTION": "N6", "GEM": "L1", "GEAR": "M2", "COFFER": "S1", "RUNE": "I2"}
ELEMENT_NAME = {"BONE": "Bone", "FIRE": "Fire", "ICE": "Ice", "LEAF": "Leaf", "VOLT": "Volt", "METAL": "Metal"}


def load(path: str) -> dict:
    return json.loads((DATA / path).read_text(encoding="utf-8"))


def frame0(path: Path) -> Image.Image:
    img = Image.open(path).convert("RGBA")
    return img.crop((0, 0, img.height, img.height))


def card(sprite: Image.Image, lines: list[tuple[str, str]], ring: str | None) -> Image.Image:
    img = Image.new("RGBA", CARD, rgba("N1"))
    d = ImageDraw.Draw(img)
    d.rectangle((0, 0, CARD[0] - 1, CARD[1] - 1), outline=rgba(ring or "N3"))
    s = sprite if sprite.width >= 32 else sprite.resize((sprite.width * 2, sprite.height * 2), Image.NEAREST)
    img.alpha_composite(s, (6 + (32 - s.width) // 2, (CARD[1] - s.height) // 2))
    y = 4
    for text, colour in lines:
        d.text((44, y), text, font=FONT, fill=rgba(colour))
        y += 10
    return img


def sheet(title: str, cards: list[Image.Image], path: Path) -> None:
    rows = (len(cards) + COLS - 1) // COLS
    w = COLS * (CARD[0] + 4) + 4
    h = 18 + rows * (CARD[1] + 4) + 4
    img = Image.new("RGBA", (w, h), rgba("N0"))
    ImageDraw.Draw(img).text((4, 4), title, font=FONT, fill=rgba("G1"))
    for i, c in enumerate(cards):
        img.alpha_composite(c, (4 + (i % COLS) * (CARD[0] + 4), 18 + (i // COLS) * (CARD[1] + 4)))
    img.resize((w * 2, h * 2), Image.NEAREST).save(path)


def recipe(u: dict, rituals: dict) -> str:
    els = [ELEMENT_NAME[e] for e in u["elements"]]
    return {
        "T1": lambda: f"Trio of {els[0]}", "ELITE": lambda: f"Quartet of {els[0]}",
        "LEGEND": lambda: f"Quintet of {els[0]}", "HYBRID": lambda: f"Duo Pact / Full Moon {els[0]}+{els[1]}",
        "RITUAL": lambda: "Ritual " + "+".join(els) + f" ({ELEMENT_NAME[rituals[u['id']]]} x2)",
        "PARADE": lambda: "Rainbow (5 different)", "WISP": lambda: "Rabble / Duo Pact with no hybrid",
    }[u["kind"]]()


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    text = {n: load(f"text/content/{n}.json") for n in
            ["units", "hunters", "trinkets", "potions", "gems", "gear", "coffers", "runes"]}
    rows: list[str] = ["# Art compilation sheets", "",
                       "Generated by `python tools/art/compile_sheets.py` from data/ and data/text/ — edit text there, "
                       "art in the PNG (or its generator), then re-run.", ""]

    units = load("units.json")["units"]
    rituals = {r["unit"]: r["core"] for r in load("combos.json")["rituals"]}
    legends = {u["id"] for u in units if u["kind"] == "LEGEND"}
    cards = []
    rows += ["## Units", "", "| Id | Name | Summoned by | Art | Generator |", "|---|---|---|---|---|"]
    for u in units:
        fname = "wisp_mask" if u["id"] == "WISP" else u["id"].lower()
        path = ROOT / f"assets/sprites/units/{fname}.png"
        gen = "tools/art/legends.py" if u["id"] in legends else "tools/art/units.py"
        how = recipe(u, rituals)
        cards.append(card(frame0(path), [(text["units"][u["id"]]["name"], "N7"), (how, "N6"),
                                         (f"units/{fname}.png", "N5")], None))
        rows.append(f"| {u['id']} | {text['units'][u['id']]['name']} | {how} | `{path.relative_to(ROOT).as_posix()}` | `{gen}` |")
    sheet("UNITS — name / summoned by / art file", cards, OUT / "units.png")

    cards = []
    enemies = load("enemies.json")
    rules = {r["id"]: r for r in enemies["boss_rules"]}
    rows += ["", "## Hunters", "", "| Id | Name | Role / rule | Art | Generator |", "|---|---|---|---|---|"]
    for e in enemies["enemies"]:
        path = ROOT / f"assets/sprites/enemies/{e['id'].lower()}.png"
        role = e["role"].title() + (f" · {text['hunters']['rules'][e['rule']]['name']}" if e["rule"] else "")
        cards.append(card(frame0(path), [(text["hunters"]["hunters"][e["id"]]["name"], "N7"), (role, "N6"),
                                         (f"enemies/{e['id'].lower()}.png", "N5")], None))
        rows.append(f"| {e['id']} | {text['hunters']['hunters'][e['id']]['name']} | {role} | "
                    f"`{path.relative_to(ROOT).as_posix()}` | `tools/art/enemies_dice.py` |")
    sheet("HUNTERS — name / role / art file", cards, OUT / "hunters.png")

    cards = []
    rows += ["", "## Items", "", "| Kind | Id | Name | Art | Generator |", "|---|---|---|---|---|"]
    groups = [
        ("RELIC", "Trinket", load("relics.json")["relics"], "trinkets", "icons/relics", "tools/art/icons.py",
         lambda r: r["rarity"].title()),
        ("POTION", "Potion", [c for c in load("consumables.json")["consumables"] if c["kind"] == "POTION"], "potions",
         "icons/consumables", "tools/art/items.py", lambda r: "Potion"),
        ("GEM", "Gem", [c for c in load("consumables.json")["consumables"] if c["kind"] == "GEM"], "gems",
         "icons/consumables", "tools/art/items.py", lambda r: "Gem"),
        ("GEAR", "Gear", load("equipment.json")["equipment"], "gear", "icons/equipment", "tools/art/icons.py",
         lambda r: "Gear"),
        ("COFFER", "Coffer", load("coffers.json")["coffers"], "coffers", "icons/coffers", "tools/art/items.py",
         lambda r: f"{r['kind'].title()} coffer · {r['size'].title()}"),
    ]
    for kind, label, items, tkey, folder, gen, sub in groups:
        for r in items:
            path = ROOT / f"assets/{folder}/{r['id'].lower()}.png"
            name = text[tkey][r["id"]]["name"]
            cards.append(card(Image.open(path).convert("RGBA"), [(name, "N7"), (sub(r), KIND_COLOUR[kind]),
                                                                 (f"{folder.split('/')[-1]}/{r['id'].lower()}.png", "N5")],
                              KIND_COLOUR[kind]))
            rows.append(f"| {label} | {r['id']} | {name} | `{path.relative_to(ROOT).as_posix()}` | `{gen}` |")
    sheet("ITEMS — trinkets (gold), potions (purple), gems (green), gear (steel), coffers", cards, OUT / "items.png")

    cards = []
    rows += ["", "## Dice, runes and glyphs", "", "| Asset | Name | Art | Generator |", "|---|---|---|---|"]
    for rune, t in text["runes"].items():
        path = ROOT / f"assets/sprites/dice/die_body_{rune.lower()}.png"
        cards.append(card(Image.open(path).convert("RGBA"), [(t["name"] + " rune", "N7"), (t["effect"][:30], "N6"),
                                                             (f"dice/die_body_{rune.lower()}.png", "N5")], "I2"))
        rows.append(f"| Rune body | {t['name']} | `{path.relative_to(ROOT).as_posix()}` | `tools/art/dice_runes.py` |")
    for e, n in ELEMENT_NAME.items():
        path = ROOT / f"assets/sprites/dice/glyph_{e.lower()}.png"
        cards.append(card(Image.open(path).convert("RGBA"), [(n + " glyph", "N7"), ("Die face element", "N6"),
                                                             (f"dice/glyph_{e.lower()}.png", "N5")], None))
        rows.append(f"| Element glyph | {n} | `{path.relative_to(ROOT).as_posix()}` | `tools/art/enemies_dice.py` |")
    sheet("DICE — rune bodies and element glyphs", cards, OUT / "dice.png")

    (OUT / "README.md").write_text("\n".join(rows) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT).as_posix()}: units, hunters, items, dice + README.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
