GLYPH_W, GLYPH_H, SPACING = 3, 5, 1


def text_width(text: str, scale: int = 1) -> int:
    if not text:
        return 0
    return (len(text) * (GLYPH_W + SPACING) - SPACING) * scale


def text_pixels(text: str, scale: int = 1) -> list[tuple[int, int]]:
    """Pixel offsets (x, y) of `text` rendered at the origin."""
    out: list[tuple[int, int]] = []
    for i, ch in enumerate(text.upper()):
        rows = _GLYPHS.get(ch, _GLYPHS["?"])
        ox = i * (GLYPH_W + SPACING) * scale
        for y, row in enumerate(rows):
            for x, c in enumerate(row):
                if c == "#":
                    for sy in range(scale):
                        for sx in range(scale):
                            out.append((ox + x * scale + sx, y * scale + sy))
    return out
