"""Validate the project's agent skills and keep the skill index in AGENTS.md in sync.

Skills live in .claude/skills/<name>/SKILL.md. This tool is the single gate for them:

    python tools/skills_index.py            # validate + check the index is in sync (exit 1 on problems)
    python tools/skills_index.py --write    # validate + regenerate the index block in AGENTS.md
    python tools/skills_index.py --hook     # session-start mode: prints the status, always exits 0

Rules enforced (see .claude/skills/skill-maintenance/SKILL.md for the why):
  - every folder under .claude/skills has a SKILL.md with YAML front matter
  - `name` is kebab-case and equals the folder name
  - `description` exists, is at most 1024 characters and contains "Use when"
  - every relative markdown link in a skill resolves to a file
  - SKILL.md stays under MAX_LINES (details belong in references/)
  - the generated block in AGENTS.md equals what this tool would write
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKILLS_DIR = ROOT / ".claude" / "skills"
INDEX_FILE = ROOT / "AGENTS.md"
BEGIN = "<!-- skills-index:begin (generated by tools/skills_index.py --write; do not edit) -->"
END = "<!-- skills-index:end -->"

NAME_RE = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
LINK_RE = re.compile(r"\]\(([^)#\s]+)(?:#[^)]*)?\)")
FENCE_RE = re.compile(r"^```.*?^```", re.MULTILINE | re.DOTALL)
MAX_DESCRIPTION = 1024
MAX_LINES = 300


def parse_front_matter(text: str) -> tuple[dict[str, str], str] | None:
    if not text.startswith("---"):
        return None
    parts = text.split("\n---", 1)
    if len(parts) != 2:
        return None
    header = parts[0][3:]
    fields: dict[str, str] = {}
    key = None
    for line in header.splitlines():
        if not line.strip():
            continue
        match = re.match(r"^([A-Za-z0-9_-]+):\s*(.*)$", line)
        if match and not line.startswith((" ", "\t")):
            key = match.group(1)
            fields[key] = match.group(2).strip()
        elif key:  # folded continuation line
            fields[key] = (fields[key] + " " + line.strip()).strip()
    for k, v in fields.items():
        if v[:1] in "\"'" and v[-1:] == v[:1]:
            fields[k] = v[1:-1]
        elif v in (">", "|", ">-", "|-"):
            fields[k] = ""
    return fields, parts[1]


def check_skill(folder: Path) -> tuple[dict[str, str] | None, list[str]]:
    errors: list[str] = []
    rel = folder.relative_to(ROOT).as_posix()
    skill_md = folder / "SKILL.md"
    if not skill_md.is_file():
        return None, [f"{rel}: missing SKILL.md"]
    text = skill_md.read_text(encoding="utf-8")
    parsed = parse_front_matter(text)
    if parsed is None:
        return None, [f"{rel}/SKILL.md: no YAML front matter (--- name / description ---)"]
    fields, body = parsed
    name = fields.get("name", "")
    desc = fields.get("description", "")
    if name != folder.name:
        errors.append(f"{rel}/SKILL.md: name '{name}' must equal folder name '{folder.name}'")
    if not NAME_RE.match(folder.name):
        errors.append(f"{rel}: folder name must be kebab-case")
    if not desc:
        errors.append(f"{rel}/SKILL.md: empty description")
    elif len(desc) > MAX_DESCRIPTION:
        errors.append(f"{rel}/SKILL.md: description is {len(desc)} chars (max {MAX_DESCRIPTION})")
    elif "Use when" not in desc:
        errors.append(f"{rel}/SKILL.md: description must say 'Use when ...' (it is how the skill gets picked)")
    lines = text.count("\n") + 1
    if lines > MAX_LINES:
        errors.append(f"{rel}/SKILL.md: {lines} lines (max {MAX_LINES}); move detail into references/")
    for md in folder.rglob("*.md"):
        prose = FENCE_RE.sub("", md.read_text(encoding="utf-8"))
        for target in LINK_RE.findall(prose):
            if "://" in target or target.startswith("mailto:"):
                continue
            if not (md.parent / target).resolve().exists():
                errors.append(f"{md.relative_to(ROOT).as_posix()}: broken link '{target}'")
    return {"name": name, "description": desc, "path": f"{rel}/SKILL.md"}, errors


def collect() -> tuple[list[dict[str, str]], list[str]]:
    skills: list[dict[str, str]] = []
    errors: list[str] = []
    if not SKILLS_DIR.is_dir():
        return skills, [f"{SKILLS_DIR.relative_to(ROOT).as_posix()} does not exist"]
    for folder in sorted(p for p in SKILLS_DIR.iterdir() if p.is_dir()):
        info, errs = check_skill(folder)
        errors.extend(errs)
        if info:
            skills.append(info)
    return skills, errors


def render_index(skills: list[dict[str, str]]) -> str:
    rows = [BEGIN, "", "| Skill | Use when | File |", "| --- | --- | --- |"]
    for s in skills:
        desc = " ".join(s["description"].split())
        use_when = desc.split("Use when", 1)[1].strip(" :") if "Use when" in desc else desc
        use_when = use_when.replace("|", "\\|")
        rows.append(f"| `{s['name']}` | {use_when} | [{s['name']}]({s['path']}) |")
    rows += ["", END]
    return "\n".join(rows)


def current_block(text: str) -> str | None:
    start, end = text.find(BEGIN), text.find(END)
    if start == -1 or end == -1 or end < start:
        return None
    return text[start : end + len(END)]


def main(argv: list[str]) -> int:
    write, hook = "--write" in argv, "--hook" in argv
    skills, errors = collect()
    wanted = render_index(skills)
    text = INDEX_FILE.read_text(encoding="utf-8") if INDEX_FILE.is_file() else ""
    block = current_block(text)

    if block is None:
        errors.append(f"AGENTS.md: skill index markers not found ({BEGIN[:24]}... / {END})")
    elif block != wanted:
        if write:
            INDEX_FILE.write_text(text.replace(block, wanted), encoding="utf-8")
            print("AGENTS.md: skill index regenerated")
        else:
            errors.append("AGENTS.md: skill index is out of date; run `python tools/skills_index.py --write`")

    names = ", ".join(s["name"] for s in skills)
    if errors:
        print(f"SKILLS CHECK FAILED ({len(errors)} problem(s)). Fix before relying on the skill index:")
        for e in errors:
            print(f"  - {e}")
        return 0 if hook else 1
    print(f"Skills OK ({len(skills)}): {names}. Follow the Skill protocol in AGENTS.md.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
